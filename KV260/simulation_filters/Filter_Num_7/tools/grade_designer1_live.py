def color_axes(rgb):
    r, g, b = np.moveaxis(rgb, -1, 0)
    return np.stack(((5*r + 9*g + 2*b + 8)//16, r-g, g-b), axis=-1)


def grade_live(native):
    h, w = native.shape[:2]
    radius = 40
    padded = np.pad(native, ((radius,radius),(radius,radius),(0,0)), mode="edge")
    directions, thresholds, widths, gains = RAMPS[:, :6], RAMPS[:, 6], RAMPS[:, 7], RAMPS[:, 8:]
    result = np.empty_like(native)
    for y in range(0, h, 32):
        end = min(y+32, h)
        centre = native[y:end].astype(np.int32)
        ring_sum = np.zeros_like(centre)
        for dy in (-radius, 0, radius):
            for dx in (-radius, 0, radius):
                if dx or dy:
                    ring_sum += padded[y+radius+dy:end+radius+dy, radius+dx:radius+dx+w]
        yuv = color_axes(centre)
        context = color_axes((ring_sum+4)//8) - yuv
        axes = np.concatenate((yuv, context), axis=2)
        ramps = np.clip(axes @ directions.T - thresholds, 0, widths)
        offset = 32*BASE[0] + axes @ BASE[1:] + ramps @ gains
        graded = np.clip(centre + (offset+64)//128, 0, 255)
        luma = yuv[...,0]
        weight = np.minimum.reduce((luma-16, 240-luma, 128-np.ptp(centre, axis=2))).clip(0,32)[...,None]
        result[y:end] = (weight*graded + (32-weight)*centre + 16)//32
    return result
